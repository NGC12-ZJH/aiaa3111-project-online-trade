"""taxonomy_v1 step 2 (LLM): proposals that a human then accepts or edits. Nothing here is final.

Three kinds of request, each on schema items only (first seen before 2010-12-01), descriptions only:
  split   one request per subcategory flagged "split" in v1_subcategory_stats.csv
  other   one request re-assigning v0 "other" items to existing or new subcategories
  design  one request choosing design lines and season keywords from frequent words (counted here, no LLM)

Outputs: data/taxonomy/v1_work/proposals/*.json, results/v1_proposals_review.md, and (only if absent)
configs/taxonomy/taxonomy_v1_decisions.json, the file the human edits before step 3.

Usage:
  python scripts/run_taxonomy.py v1_step2_propose --dry-run                 # show prompt sizes, no API call
  python scripts/run_taxonomy.py v1_step2_propose --only split:toys_games    # one request
  python scripts/run_taxonomy.py v1_step2_propose                            # everything (cached; rerun resumes)
"""
import argparse
import json
import re
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from string import Template

import pandas as pd

from .llm_client import LLM, BudgetExceeded, load_config, parse_json
from .paths import RESULTS, SCHEMA_CUTOFF
from .taxonomy_io import LLM_CACHE, PROMPTS, TAX_CFG, V1_WORK, gold_codes, load_catalog, load_embeddings, pick_examples, prefix

PROP = V1_WORK / "proposals"
PROP.mkdir(parents=True, exist_ok=True)
STOP = set("""SET OF AND THE WITH IN FOR PACK SMALL LARGE MINI JUMBO DESIGN ASSORTED COLOUR RED PINK BLUE GREEN WHITE
BLACK IVORY CREAM YELLOW PURPLE ORANGE SILVER GOLD BROWN GREY NATURAL CLEAR PASTEL BRIGHT LILAC TURQUOISE""".split())


def items_block(df):
    return "\n".join(f"{r.stock_code} | {r.canonical_description}" for r in df.itertuples())


def requests(cat, E, stats):
    schema = cat[cat.first_seen < SCHEMA_CUTOFF].sort_values("stock_code")
    existing = sorted(set(cat.l2_id) - {"other"})
    gold_fam = {prefix(c) for c in gold_codes()}
    seeds = cat[cat.label_source == "rule"][["stock_code", "l2_id"]]
    excl = set(cat.stock_code[cat.stock_code.map(prefix).isin(gold_fam)])
    out = {}
    t = Template((PROMPTS / "propose_split_v1.txt").read_text())
    for r in stats[stats.flag == "split"].itertuples():
        g = schema[schema.l2_id == r.l2_id]
        others = [e for e in existing if e != r.l2_id]
        out[f"split:{r.l2_id}"] = t.substitute(l2_id=r.l2_id, l1_id=r.l1_id, n=len(g), items=items_block(g),
                                               existing_ids=", ".join(others))
    l1_of = cat.drop_duplicates("l2_id").set_index("l2_id").l1_id
    tax = "\n".join(f"{l2} | {l1_of[l2]} | " + "; ".join(pick_examples(cat, E, seeds, l2, excl, 4)) for l2 in existing)
    g = schema[schema.l2_id == "other"]
    out["other"] = Template((PROMPTS / "reassign_other_v1.txt").read_text()).substitute(n=len(g), taxonomy=tax, items=items_block(g))
    out["design"] = Template((PROMPTS / "design_lines_v1.txt").read_text()).substitute(candidates=design_candidates(schema))
    return out


def design_candidates(schema, top=150):
    codes, types, samples = defaultdict(set), defaultdict(set), defaultdict(list)
    for r in schema.itertuples():
        w = [x for x in re.findall(r"[A-Z][A-Z']+", r.canonical_description) if len(x) >= 3]
        grams = {x for x in w if x not in STOP} | {f"{a} {b}" for a, b in zip(w, w[1:]) if a not in STOP and b not in STOP}
        for gm in grams:
            codes[gm].add(r.stock_code)
            types[gm].add(r.l2_id)
            if len(samples[gm]) < 4:
                samples[gm].append(r.canonical_description)
    cand = [(gm, len(codes[gm]), len(types[gm])) for gm in codes if len(codes[gm]) >= 6 and len(types[gm]) >= 4]
    cand.sort(key=lambda x: (-x[2], -x[1], x[0]))
    return "\n".join(f"{gm} | items={n} | types={k} | " + "; ".join(samples[gm]) for gm, n, k in cand[:top])


def validate(name, obj, cat):
    if name.startswith("split:"):
        l2 = name.split(":", 1)[1]
        want = set(cat[(cat.l2_id == l2) & (cat.first_seen < SCHEMA_CUTOFF)].stock_code)
        ids = {s["id"] for s in obj.get("subcategories", [])} | (set(cat.l2_id) - {"other", l2})
    elif name == "other":
        want = set(cat[(cat.l2_id == "other") & (cat.first_seen < SCHEMA_CUTOFF)].stock_code)
        ids = set(cat.l2_id) | {s["id"] for s in obj.get("new_subcategories", [])}
    else:
        return {}
    a = obj.get("assignments", {})
    return {"missing_items": sorted(want - set(a)), "unknown_items": sorted(set(a) - want),
            "invalid_ids": sorted({v for v in a.values() if v not in ids})}


def review_md(results, stats):
    lines = ["# taxonomy_v1 proposals for human review", "",
             "Generated by `v1_step2_propose.py`. **Draft LLM suggestions; accept, edit or reject each one in "
             "`configs/taxonomy/taxonomy_v1_decisions.json`.**", ""]
    for name, (obj, chk) in results.items():
        lines += [f"## {name}", ""]
        if name == "design":
            for d in obj.get("design_lines", []):
                lines.append(f"- design_line `{d['id']}` ({d.get('name', '')}): {', '.join(d.get('patterns', []))}")
            for s, p in obj.get("seasons", {}).items():
                lines.append(f"- season `{s}`: {', '.join(p)}")
        else:
            subs = obj.get("subcategories") or obj.get("new_subcategories") or []
            counts = pd.Series(obj.get("assignments", {})).value_counts()
            for s in subs:
                lines.append(f"- `{s['id']}` {s.get('name_zh', '')} / {s.get('name_en', '')} — {counts.get(s['id'], 0)} items. "
                             f"{s.get('definition', '')} *Boundary:* {s.get('boundary', '')}")
            sub_ids = {s['id'] for s in subs}
            moved = {k: int(v) for k, v in counts.items() if k not in sub_ids}
            if moved:
                lines.append(f"- moved to existing subcategories: {moved}")
            if chk:
                lines.append(f"- checks: missing {len(chk['missing_items'])}, unknown {len(chk['unknown_items'])}, "
                             f"invalid ids {chk['invalid_ids']}")
        if obj.get("comment"):
            lines.append(f"- comment: {obj['comment']}")
        lines.append("")
    (RESULTS / "v1_proposals_review.md").write_text("\n".join(lines))


def decisions_template(results, stats):
    f = TAX_CFG / "taxonomy_v1_decisions.json"
    if f.exists():
        return
    d = {"_comment": "Edit by hand, then run v1_step3_build.py. accept=false keeps the v0 subcategory unchanged.",
         "splits": {n.split(":", 1)[1]: {"accept": True, "edits": {}} for n in results if n.startswith("split:")},
         "merge": {r.l2_id: "garden_outdoor" for r in stats[stats.flag == "merge"].itertuples()},
         "other": {"accept_assignments": True, "accept_new_subcategories": True},
         "design": {"accept": True}}
    f.write_text(json.dumps(d, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="request names, e.g. split:toys_games other design")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--max-cost", type=float)
    ap.add_argument("--model")
    ap.add_argument("--max-tokens", type=int, default=32000)
    a = ap.parse_args()
    cat, E = load_catalog(), load_embeddings()
    stats = pd.read_csv(RESULTS / "v1_subcategory_stats.csv")
    reqs = requests(cat, E, stats)
    names = a.only or list(reqs)
    if a.dry_run:
        for n in names:
            print(f"{n:32s} ~{len(reqs[n]) // 4:6d} prompt tokens")
        print("\n----- first prompt -----\n" + reqs[names[0]][:3000])
        raise SystemExit
    llm = LLM(load_config(a.model), LLM_CACHE, max_cost=a.max_cost)
    results = {}

    def run(n):
        rec = llm.chat([{"role": "user", "content": reqs[n]}], meta={"task": "v1_propose", "request": n},
                       max_tokens=a.max_tokens)
        if rec["finish_reason"] != "stop":
            return n, rec, None, f"finish_reason={rec['finish_reason']} (output cut off; rerun with a larger --max-tokens)"
        try:
            return n, rec, parse_json(rec["content"]), None
        except (json.JSONDecodeError, TypeError, IndexError) as e:
            return n, rec, None, f"unparseable JSON: {e}"

    print(f"sending {len(names)} requests in parallel (reasoning model: each may take several minutes)...", flush=True)
    with ThreadPoolExecutor(max_workers=len(names)) as pool:
        futs = [pool.submit(run, n) for n in names]
        for f in as_completed(futs):
            try:
                n, rec, obj, err = f.result()
            except BudgetExceeded as e:
                print("STOP (budget):", e)
                continue
            if err:
                print(f"{n:32s} FAILED: {err} | cost={rec['cost']:.4f}", flush=True)
                continue
            chk = validate(n, obj, cat)
            (PROP / f"{n.replace(':', '__')}.json").write_text(json.dumps({"request": n, "cache_key": rec["key"],
                                                                           "checks": chk, "proposal": obj}, indent=1, ensure_ascii=False))
            results[n] = (obj, chk)
            u = rec["usage"]
            print(f"{n:32s} cached={rec['from_cache']!s:5s} cost={rec['cost']:.4f} out={u['completion_tokens']} "
                  f"(reasoning {u['reasoning_tokens']}) checks={ {k: len(v) for k, v in chk.items()} }", flush=True)
    # include proposals already on disk from earlier runs
    for f in sorted(PROP.glob("*.json")):
        p = json.loads(f.read_text())
        results.setdefault(p["request"], (p["proposal"], p["checks"]))
    review_md(dict(sorted(results.items())), stats)
    decisions_template(results, stats)
    print(json.dumps(llm.summary(), indent=1))
